const LANGS = ['fr', 'en'];

function resolveLang(input) {
  return LANGS.includes(input) ? input : 'fr';
}

function translator(lang) {
  const l = resolveLang(lang);
  return (key) => (DICT[l] && DICT[l][key]) || (DICT.fr[key] || key);
}

module.exports = { DICT, LANGS, resolveLang, translator };
