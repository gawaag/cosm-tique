const LANGS = ['ar', 'fr'];

function resolveLang(input) {
  return LANGS.includes(input) ? input : 'ar';
}

function translator(lang) {
  const l = resolveLang(lang);
  return (key) => (DICT[l] && DICT[l][key]) || (DICT.fr[key] || key);
}

function htmlDir(lang) {
  return resolveLang(lang) === 'ar' ? 'rtl' : 'ltr';
}

const AR_MONTHS = ['يناير', 'فبراير', 'مارس', 'أبريل', 'ماي', 'يونيو', 'يوليوز', 'غشت', 'شتنبر', 'أكتوبر', 'نونبر', 'دجنبر'];
const FR_MONTHS = ['janvier', 'février', 'mars', 'avril', 'mai', 'juin', 'juillet', 'août', 'septembre', 'octobre', 'novembre', 'décembre'];

function formatReviewDate(iso, lang) {
  const parts = String(iso || '').split('-');
  if (parts.length !== 3) return iso || '';
  const y = parts[0];
  const m = Number(parts[1]);
  const d = parseInt(parts[2], 10);
  if (!m || m < 1 || m > 12 || !d) return iso || '';
  if (resolveLang(lang) === 'ar') return `${d} ${AR_MONTHS[m - 1]} ${y}`;
  return `${d} ${FR_MONTHS[m - 1]} ${y}`;
}

module.exports = { DICT, LANGS, resolveLang, translator, htmlDir, formatReviewDate };
